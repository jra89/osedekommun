function get_lang() {
    if (isset($_GET['lang']) && ($_GET['lang'] == 'en' || $_GET['lang'] == 'sv')) {
        if (!headers_sent() && !isset($GLOBALS['osedelang_cookie_set'])) {
            $GLOBALS['osedelang_cookie_set'] = 1;
            setcookie('osedelang', $_GET['lang'], time() + 86400 * 30, '/');
        }
        return $_GET['lang'];
    }
    if (isset($_COOKIE['osedelang']) && ($_COOKIE['osedelang'] == 'en' || $_COOKIE['osedelang'] == 'sv')) {
        return $_COOKIE['osedelang'];
    }
    return 'sv';
}

