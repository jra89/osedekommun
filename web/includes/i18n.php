function t($key) {
    $l = get_lang();
    if (isset($GLOBALS['STRINGS'][$l][$key])) return $GLOBALS['STRINGS'][$l][$key];
    return $key;
}

function lang_param() {
    $l = get_lang() == 'sv' ? 'en' : 'sv';
    return '?lang=' . $l;
}

function lang_url() {
    $l = get_lang() == 'sv' ? 'en' : 'sv';
    $uri = isset($_SERVER['REQUEST_URI']) ? $_SERVER['REQUEST_URI'] : '/';
    $base = strtok($uri, '?');
    $params = array();
    parse_str(isset($_SERVER['QUERY_STRING']) ? $_SERVER['QUERY_STRING'] : '', $params);
    $params['lang'] = $l;
    return $base . '?' . http_build_query($params);
}
